#!/usr/bin/env python3
"""Generate common QX downloads from curated leaves; never fetch external rules."""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import tempfile

from build_config import ROOT, category_rules, load_categories, remote_resources, serialize


def generate_bundles(root=ROOT):
    """Return deterministic owned paths and text, preserving source notices."""
    categories = load_categories(root=root)
    by_path = {item['path']: item for item in categories}
    result = {}
    for resource in remote_resources(categories, root):
        if not resource['path'].startswith('Bundles/'):
            continue
        lines = [
            f"# Generated Quantumult X common resource: {resource['tag']}",
            '# Generated by scripts/build_bundles.py; edit the source leaves, not this file.',
            '# Ordered membership: Config/categories.json; complete source notices retained below.',
            f"# Effective policy: {resource['policy']}",
        ]
        for source in resource['source_paths']:
            item = by_path[source]
            rules = category_rules(item, root)
            replacements = {rule.line: serialize(rule) for rule in rules}
            lines.extend(['', f'# Source leaf: {source}'])
            for number, line in enumerate((root / source).read_text().splitlines(), 1):
                lines.append(replacements.get(number, line))
        result[resource['path']] = '\n'.join(lines).rstrip() + '\n'
    return result


def write_bundles(root=ROOT):
    """Explicitly publish generated local files; profile builds do not call this."""
    bundles = generate_bundles(root)
    for relative, text in bundles.items():
        output = root / relative
        output.parent.mkdir(parents=True, exist_ok=True)
        temp_path = None
        try:
            with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=output.parent,
                                             prefix='.qx-bundle-', delete=False) as handle:
                temp_path = Path(handle.name)
                os.fchmod(handle.fileno(), 0o644)
                handle.write(text)
            os.replace(temp_path, output)
        finally:
            if temp_path is not None:
                temp_path.unlink(missing_ok=True)
    return bundles


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='Write reviewed deterministic bundle files')
    mode.add_argument('--check', action='store_true', help='Fail when committed bundle files differ')
    args = parser.parse_args()
    if not args.check:
        bundles = write_bundles()
        print(f'Generated {len(bundles)} common resources')
    else:
        bundles = generate_bundles()
        stale = [path for path, text in bundles.items()
                 if not (ROOT / path).is_file() or (ROOT / path).read_text() != text]
        extras = sorted(str(path.relative_to(ROOT)) for path in (ROOT / 'Bundles').glob('*.list')
                        if str(path.relative_to(ROOT)) not in bundles)
        if stale or extras:
            parser.exit(1, f'Bundle drift: stale={stale}, undeclared={extras}\n')
        print(f'Verified {len(bundles)} common resources')


if __name__ == '__main__':
    main()
